function HS(e) {
  switch (e) {
    case `beforetoggle`:
    case `cancel`:
    case `click`:
    case `close`:
    case `contextmenu`:
    case `copy`:
    case `cut`:
    case `auxclick`:
    case `dblclick`:
    case `dragend`:
    case `dragstart`:
    case `drop`:
    case `focusin`:
    case `focusout`:
    case `input`:
    case `invalid`:
    case `keydown`:
    case `keypress`:
    case `keyup`:
    case `mousedown`:
    case `mouseup`:
    case `paste`:
    case `pause`:
    case `play`:
    case `pointercancel`:
    case `pointerdown`:
    case `pointerup`:
    case `ratechange`:
    case `reset`:
    case `resize`:
    case `seeked`:
    case `submit`:
    case `touchcancel`:
    case `touchend`:
    case `touchstart`:
    case `volumechange`:
    case `change`:
    case `selectionchange`:
    case `compositionstart`:
    case `compositionend`:
    case `compositionupdate`:
    case `beforeinput`:
    case `blur`:
    case `fullscreenchange`:
    case `focus`:
    case `hashchange`:
    case `popstate`:
    case `select`:
    case `selectstart`:
      return nS
    case `drag`:
    case `dragenter`:
    case `dragexit`:
    case `dragleave`:
    case `dragover`:
    case `mousemove`:
    case `mouseout`:
    case `mouseover`:
    case `pointermove`:
    case `pointerout`:
    case `pointerover`:
    case `scroll`:
    case `touchmove`:
    case `wheel`:
    case `mouseenter`:
    case `mouseleave`:
    case `pointerenter`:
    case `pointerleave`:
      return eS
    case `message`:
      switch ((0, qb.unstable_getCurrentPriorityLevel)()) {
        case qb.unstable_ImmediatePriority:
          return nS
        case qb.unstable_UserBlockingPriority:
          return eS
        case qb.unstable_NormalPriority:
        case qb.unstable_LowPriority:
          return tS
        case qb.unstable_IdlePriority:
          return rS
        default:
          return tS
      }
    default:
      return tS
  }
}
